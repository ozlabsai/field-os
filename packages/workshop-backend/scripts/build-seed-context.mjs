// Bundles a directory of seed context collections into a generated TypeScript module, so the
// Worker can install them with no network access when a deployment first serves /api.
//
// Mirrors build-format-blueprints.mjs deliberately, including the override: the directory defaults
// to this package's `seed-context/`, and `SEED_CONTEXT_DIR` points somewhere else. This repo is
// often a submodule, so a fork cannot add files here without conflicting on every update -- it
// keeps its own sample data in its own tree and points the build at it. Whatever directory is
// named *is* the deployment's seed set; it replaces this one rather than adding to it.
//
// A collection is a directory holding `collection.json` plus one `.md` file per document. Content
// is text, so unlike the blueprint archives it is emitted verbatim rather than base64.

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");
const sourceDir = resolve(pkgRoot, process.env.SEED_CONTEXT_DIR ?? "seed-context");
const outFile = join(pkgRoot, "src", "generated", "seed-context.ts");

// A document's description is its first non-empty line, so the curated summary lives with the
// content instead of in a parallel index that drifts from it. The line is dropped from the body:
// repeating it as the first line of the document would read as a stray sentence above the title.
function splitDescription(markdown) {
  const lines = markdown.split("\n");
  const index = lines.findIndex(line => line.trim() !== "");
  if (index === -1) return { description: "", body: markdown };
  return {
    description: lines[index].trim(),
    body: lines.slice(index + 1).join("\n").replace(/^\n+/, ""),
  };
}

async function readCollection(dir, name) {
  const metaPath = join(dir, "collection.json");
  let meta;
  try {
    meta = JSON.parse(await readFile(metaPath, "utf8"));
  } catch (e) {
    throw new Error(`${name}: cannot read collection.json (${e.message})`, { cause: e });
  }

  for (const field of ["collectionKey", "title", "description"]) {
    if (typeof meta[field] !== "string" || meta[field].trim() === "") {
      throw new Error(`${name}: collection.json is missing a non-empty "${field}"`);
    }
  }

  const documents = [];
  for (const file of (await readdir(dir)).toSorted()) {
    if (!file.endsWith(".md")) continue;
    const { description, body } = splitDescription(await readFile(join(dir, file), "utf8"));
    if (body.trim() === "") throw new Error(`${name}/${file}: no content below the description`);
    documents.push({ path: file, description, body });
  }

  if (documents.length === 0) {
    throw new Error(`${name}: no .md documents; an empty collection would install nothing`);
  }

  return {
    collectionKey: meta.collectionKey,
    title: meta.title,
    description: meta.description,
    icon: typeof meta.icon === "string" ? meta.icon : undefined,
    documents,
  };
}

const entries = [];
let dirents;
try {
  dirents = await readdir(sourceDir, { withFileTypes: true });
} catch (e) {
  // A deployment that wants no seed content points SEED_CONTEXT_DIR at an empty or absent
  // directory; that is a choice, not a build failure.
  if (e.code !== "ENOENT") throw e;
  dirents = [];
}

for (const dirent of dirents.toSorted((a, b) => a.name.localeCompare(b.name))) {
  if (!dirent.isDirectory()) continue;
  entries.push(await readCollection(join(sourceDir, dirent.name), dirent.name));
}

const keys = entries.map(e => e.collectionKey);
const duplicate = keys.find((key, i) => keys.indexOf(key) !== i);
if (duplicate) {
  // Installation is keyed on collectionKey, so a duplicate would have two directories fighting
  // over one collection -- last writer wins, silently.
  throw new Error(`duplicate collectionKey ${JSON.stringify(duplicate)} across seed directories`);
}

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, `// GENERATED by scripts/build-seed-context.mjs -- do not edit.
// Source: ${process.env.SEED_CONTEXT_DIR ?? "seed-context"}/

/** One document inside a seeded collection. */
export interface SeedContextDocument {
  /** Document path within the collection, e.g. "site-visits.md". */
  path: string;
  /** One-line summary, taken from the file's first non-empty line. */
  description: string;
  /** Markdown body, with the description line removed. */
  body: string;
}

/** A context collection shipped with the deployment and installed on first use. */
export interface SeedContextCollection {
  /** Stable identity across renames. Changing it orphans the installed collection. */
  collectionKey: string;
  /** Collection title as shown in the Context Library. */
  title: string;
  /** One-line description shown beside the title. */
  description: string;
  /** Optional emoji icon. */
  icon?: string;
  /** The documents to install, in path order. */
  documents: SeedContextDocument[];
}

/** Every seeded collection bundled into this build. Empty when the deployment ships none. */
export const SEED_CONTEXT: SeedContextCollection[] = ${JSON.stringify(entries, null, 2)};
`);

console.log(`seed context: ${entries.length} collection(s), ` +
    `${entries.reduce((n, e) => n + e.documents.length, 0)} document(s) -> ` +
    `src/generated/seed-context.ts`);
